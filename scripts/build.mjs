/**
 * Deterministically package standard CommonJS source for DSH's synchronous
 * module-loader factory. Source is wrapped verbatim, never eval'd or rewritten.
 * React remains a host dependency. No install or third-party build tool is needed.
 */
import assert from "node:assert/strict";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, posix } from "node:path";
import { fileURLToPath } from "node:url";
import { Script } from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const verify = process.argv.includes("--check");
const clientRoot = join(root, "src/client");
const modules = new Map();
const outputs = new Map();

async function visit(id) {
	if (modules.has(id)) return;
	assert.ok(!id.startsWith("../") && !posix.isAbsolute(id) && id.endsWith(".cjs"), `invalid source module: ${id}`);
	const source = await readFile(join(clientRoot, id), "utf8");
	new Script(`(function(require, module, exports) {\n${source}\n})`, { filename: `src/client/${id}` });
	const imports = [...source.matchAll(/\brequire\s*\(\s*(["'])([^"']+)\1\s*\)/g)];
	assert.equal(imports.length, [...source.matchAll(/\brequire\s*\(/g)].length, `use static require() calls in ${id}`);
	const dependencies = Object.create(null);
	modules.set(id, { source, dependencies });
	for (const [, , specifier] of imports) {
		if (specifier.startsWith(".")) {
			const target = posix.normalize(posix.join(posix.dirname(id), specifier));
			dependencies[specifier] = target;
			await visit(target);
		} else {
			assert.equal(specifier, "react", `unsupported host dependency in ${id}: ${specifier}`);
			dependencies[specifier] = null;
		}
	}
}

await visit("index.cjs");
const factories = [...modules].map(([id, { source }]) =>
	`${JSON.stringify(id)}: function(require, module, exports) {\n${source.trimEnd()}\n}`,
).join(",\n");
const dependencies = Object.fromEntries([...modules].map(([id, value]) => [id, value.dependencies]));
const banner = "/* Generated by npm run build. Edit src/; do not edit lib/ directly. */\n";
const client = `${banner}window.__ModuleLoader__.load({
	id: "dsh-theme-caishen",
	factory: (hostRequire) => {
		const factories = {\n${factories}\n};
		const dependencies = ${JSON.stringify(dependencies)};
		const cache = Object.create(null);
		function load(id) {
			if (cache[id]) return cache[id].exports;
			const module = { exports: {} };
			cache[id] = module;
			const localRequire = (specifier) => {
				if (!Object.prototype.hasOwnProperty.call(dependencies[id], specifier)) {
					throw new Error("Undeclared dependency in " + id + ": " + specifier);
				}
				const target = dependencies[id][specifier];
				return target === null ? hostRequire(specifier) : load(target);
			};
			try {
				factories[id](localRequire, module, module.exports);
			} catch (error) {
				delete cache[id];
				throw error;
			}
			return module.exports;
		}
		return load("index.cjs");
	}
});
`;
new Script(client, { filename: "lib/client.js" });
outputs.set("lib/client.js", client);

// The order is intentional: responsive rules precede later library overrides,
// preserving the original theme cascade during this structural refactor.
const styleFiles = ["base.css", "hero.css", "cards.css", "chrome.css", "decorations.css", "responsive.css", "prompt-library.css", "prompt-safety.css", "prompt-transfer.css", "prompt-browser.css", "layout.css", "appearance.css", "host-adapter.css", "accessibility.css", "scopes-merit.css", "fortune.css", "appearance-page.css"];
const styles = await Promise.all(styleFiles.map(async (file) =>
	`/* Source: src/client/styles/${file} */\n${(await readFile(join(clientRoot, "styles", file), "utf8")).trimEnd()}\n`,
));
outputs.set("lib/client.css", `${banner}${styles.join("\n")}`);

for (const entry of (await readdir(join(root, "src/host"))).sort()) {
	assert.ok(entry.endsWith(".js"), `unexpected host source: ${entry}`);
	outputs.set(`lib/host/${entry}`, banner + await readFile(join(root, "src/host", entry), "utf8"));
}
outputs.set("lib/index.js", banner + 'export { apply } from "./host/index.js";\n');
for (const [file, contents] of outputs) {
	if (verify) {
		let current;
		try { current = await readFile(join(root, file), "utf8"); } catch { /* Report the same build hint for missing outputs. */ }
		assert.ok(current === contents, `${file} is stale or missing; run npm run build`);
	} else {
		await mkdir(dirname(join(root, file)), { recursive: true });
		await writeFile(join(root, file), contents);
	}
}
console.log(`ok — ${verify ? "verified" : "built"} ${modules.size} client modules, ${styleFiles.length} stylesheets and ${outputs.size} runtime files`);
